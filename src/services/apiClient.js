// السياق: يحل ثغرة تسريب توكن الـ OMS المحلي إلى خدمات خارجية (Frontend Audit - Section 2)
// ==============================================================================
import axios from 'axios';

const apiClient = axios.create({
  baseURL: 'https://smarterp.top/api/v3',
  headers: {
    'Accept': 'application/json',
    'Content-Type': 'application/json'
  }
});

// ==============================================================================
// تاريخ التعديل: 2026-07-22
// الوظيفة: معالجة طلبات الـ ERP الخارجية دون تمرير توكن الـ OMS المحتفظ به محلياً
// ==============================================================================
apiClient.interceptors.request.use((config) => {
  // حظر إرفاق توكن النظام المحلي (OMS JWT) مع الطلبات الموجهة لخدمات ERP خارجية لمنع التسريب
  return config;
}, (error) => {
  return Promise.reject(error);
});

// ==============================================================================
// تاريخ التعديل: 2026-07-22
// الوظيفة: معالجة استجابات وأخطاء خدمات الـ ERP
// ==============================================================================
apiClient.interceptors.response.use(
  (response) => response,
  (error) => {
    return Promise.reject(error);
  }
);

export default apiClient;
